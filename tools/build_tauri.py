"""Build the native host and optionally package a local runnable candidate."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from build_release import payload, validate  # noqa: E402
from tools.windows_support import source_manifest  # noqa: E402


def source_inputs():
    result = {
        p.relative_to(ROOT).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in (ROOT / "desktop").rglob("*")
        if p.is_file() and not {"bin", "target", "gen", "autogenerated"}.intersection(p.relative_to(ROOT / "desktop").parts)
    }
    icon = ROOT / "app/static/workbench.ico"
    result[icon.relative_to(ROOT).as_posix()] = hashlib.sha256(icon.read_bytes()).hexdigest()
    return result


def local_roots():
    roots = [(Path.home(), "user"),
             (Path(os.environ.get("CARGO_HOME", Path.home() / ".cargo")), "cargo"),
             (Path(os.environ.get("RUSTUP_HOME", Path.home() / ".rustup")), "rustup"),
             (ROOT, "app")]
    return [(str(alias), label) for path, label in roots for alias in dict.fromkeys((path.absolute(), path.resolve()))]


def build_environment():
    environment = {**os.environ, "CARGO_TARGET_DIR": str(ROOT / "dist" / "tauri-target")}
    encoded = environment.get("CARGO_ENCODED_RUSTFLAGS")
    flags = encoded.split("\x1f") if encoded else environment.get("RUSTFLAGS", "").split()
    for path, label in local_roots():
        flags.append("--remap-path-prefix=" + path + "=" + label)
        if os.name == "nt":
            flags.append("--remap-path-prefix=\\\\?\\" + path + "=" + label)
    environment["CARGO_ENCODED_RUSTFLAGS"] = "\x1f".join(flags)
    return environment


def validate_native_paths(data):
    lowered = data.lower()
    for path, _ in local_roots():
        for spelling in (path, path.replace("\\", "/")):
            if spelling.lower().encode().lower() in lowered or spelling.lower().encode("utf-16-le").lower() in lowered:
                raise ValueError("Native artifact contains local build paths; inspect path remapping")


def build():
    environment = build_environment()
    command = ["cargo", "build", "--release", "--locked", "--manifest-path", "desktop/Cargo.toml", "--jobs", "4"]
    subprocess.run(command, cwd=ROOT, env=environment, check=True)
    candidate = ROOT / "dist/tauri-target/release/us-grid-desktop.exe"
    validate_native_paths(candidate.read_bytes())
    destination = ROOT / "desktop/bin/us-grid-desktop.exe"
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(candidate, destination)
    receipt = {
        "artifact_sha256": hashlib.sha256(destination.read_bytes()).hexdigest(),
        "source_inputs": source_inputs(), "command": command,
        "rustc": subprocess.check_output(["rustc", "--version"], text=True).strip(),
        "build_path_remapping": "Project, user home and Rust stores use logical roots",
        "sac_compatibility": "NOT_TESTED", "publication": "LOCAL_CANDIDATE",
    }
    destination.with_name("BUILD.json").write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
    return destination


def write_distribution(data, track):
    """One source payload, two delivery tracks; never replace an edited checkout."""
    data = dict(data)
    fingerprint = hashlib.sha256(b"".join(k.encode() + v for k, v in sorted(data.items()))).hexdigest()
    release = {"name": "kgi-us-grid-web", "edition": "tauri-desktop", "type": track,
               "published": False, "content_fingerprint": fingerprint}
    data["RELEASE.json"] = (json.dumps(release, indent=2) + "\n").encode()
    manifest = {"candidate": "Tauri with automatic loopback port", "distribution": track, "published": False,
                "content_fingerprint": fingerprint,
                "files": {k: hashlib.sha256(v).hexdigest() for k, v in sorted(data.items())}}
    data["CANDIDATE.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    data["SHA256SUMS"] = "".join(hashlib.sha256(v).hexdigest()+"  "+k+"\n" for k, v in sorted(data.items())).encode()
    suffix = "source-local-" if track == "source" else "windows-x64-local-"
    destination = ROOT / "dist" / ("US-Grid-Workbench-Tauri-" + suffix + fingerprint[:10] + ".zip")
    destination.parent.mkdir(parents=True, exist_ok=True)
    if not destination.exists():
        with zipfile.ZipFile(destination, "x", zipfile.ZIP_DEFLATED) as archive:
            for name, content in sorted(data.items()):
                entry = zipfile.ZipInfo("US-Grid-Workbench/"+name, (1980, 1, 1, 0, 0, 0))
                entry.compress_type = zipfile.ZIP_DEFLATED
                archive.writestr(entry, content)
    with zipfile.ZipFile(destination) as archive:
        expected = {"US-Grid-Workbench/"+k for k in data}
        if set(archive.namelist()) != expected or archive.testzip() is not None or any(
            archive.read("US-Grid-Workbench/"+name) != content for name, content in data.items()
        ):
            raise ValueError("Existing archive differs; preserve it and inspect")
    destination.with_suffix(".zip.sha256").write_text(hashlib.sha256(destination.read_bytes()).hexdigest() + "  " + destination.name + "\n")
    if track == "source":
        folder = ROOT / "dist" / ("tauri-source-"+fingerprint[:10])
        if folder.exists():
            actual = {p.relative_to(folder).as_posix() for p in folder.rglob("*") if p.is_file()}
            if (folder / ".git").exists() or actual != set(data) or any((folder/k).read_bytes() != v for k,v in data.items()):
                raise ValueError("Source projection was edited; never replace it")
        else:
            for name, content in data.items():
                target = folder / name
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(content)
    return destination


def source_package():
    data = payload()
    validate(data)
    return write_distribution(data, "source")


def package():
    executable = ROOT / "desktop/bin/us-grid-desktop.exe"
    receipt = json.loads(executable.with_name("BUILD.json").read_text(encoding="utf-8"))
    if receipt["source_inputs"] != source_inputs() or receipt["artifact_sha256"] != hashlib.sha256(executable.read_bytes()).hexdigest():
        raise ValueError("Native source or artifact changed; build before packaging")
    data = payload()
    validate(data)
    for name in ("us-grid-desktop.exe", "BUILD.json"):
        data["desktop/bin/" + name] = (executable.parent / name).read_bytes()
    dependencies = source_manifest(data)
    dependencies["scope"] = "WINDOWS_RUNNABLE_PACKAGE"
    dependencies["native_runtime"] = "TAURI_INCLUDED_PYTHON_PREPARED_AT_INSTALLATION"
    dependencies["limitations"][0] = "Python, uv and wheel native payloads are prepared at installation; inspect those installed files separately."
    dependencies["tauri_desktop"] = {
        "path": "desktop/bin/us-grid-desktop.exe", "tauri_version": "2.12.6",
        "sha256": receipt["artifact_sha256"], "webview": "WebView2 Evergreen Runtime",
        "sac_compatibility": "NOT_TESTED", "production_signed": False,
    }
    data["WINDOWS-DEPENDENCIES.json"] = (json.dumps(dependencies, ensure_ascii=False, indent=2) + "\n").encode()
    return write_distribution(data, "windows-runnable")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--package", action="store_true")
    parser.add_argument("--package-only", action="store_true")
    parser.add_argument("--source-only", action="store_true")
    arguments = parser.parse_args()
    if arguments.source_only:
        print(source_package())
        raise SystemExit(0)
    if not arguments.package_only:
        print(build())
    if arguments.package or arguments.package_only:
        print(source_package())
        print(package())
